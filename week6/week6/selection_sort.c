#include <stdio.h>

int main() {

    // 정렬할 배열
    int arr[] = {5, 3, 8, 1, 2};

    // 배열의 크기
    int n = 5;

    // 반복문에 사용할 변수
    int i, j;

    // 가장 작은 값의 위치를 저장할 변수
    int min;

    // 두 값을 바꿀 때 사용하는 임시 변수
    int temp;


    // 첫 번째 위치부터 하나씩 정렬
    // 마지막 하나는 자동으로 정렬되기 때문에 n - 1번 반복
    for (i = 0; i < n - 1; i++) {

        // 일단 현재 위치를 가장 작은 값이라고 가정
        min = i;


        // 현재 위치 다음부터 배열의 끝까지 비교
        for (j = i + 1; j < n; j++) {

            // 현재 최솟값보다 더 작은 값을 발견하면
            if (arr[j] < arr[min]) {

                // 그 값의 위치를 min에 저장
                min = j;
            }
        }


        // 현재 위치의 값과 가장 작은 값을 서로 교환

        // 현재 값을 임시 변수에 저장
        temp = arr[i];

        // 가장 작은 값을 현재 위치로 이동
        arr[i] = arr[min];

        // 원래 현재 위치의 값을 최솟값이 있던 위치로 이동
        arr[min] = temp;
    }


    // 정렬된 배열 출력
    for (i = 0; i < n; i++) {

        // 배열의 각 값을 출력
        printf("%d ", arr[i]);
    }

    return 0;
}